    <div style="max-width:1200px;margin:0 auto;">
        <h2 style="font-size:26px;color:#12203f;margin:0 0 8px 0;">How Does a Dissertation Differ From a Thesis?</h2>
        <p style="font-size:16px;line-height:1.7;color:#2b2f38;margin:0 0 24px 0;">One of the most common questions we
            get from students is surprisingly simple on the surface, yet it trips up even final-year scholars: "Is my
            final project a thesis or a dissertation?" The confusion isn't really the student's fault — universities
            across different countries use these two terms in completely opposite ways, so a definition that holds true
            in one part of the world can be entirely wrong in another. A student who has read guidance written for a US
            university ends up applying the wrong structure, technique, format, length, and research expectations to a
            project meant for a UK or Canadian institution, which can cost them marks. That's exactly why we've broken
            down the real, region-specific differences below:</p>

        <div style="overflow-x:auto;">
            <table style="width:100%;border-collapse:collapse;font-size:14px;">
                <tr style="background:#12203f;">
                    <th style="padding:14px 16px;text-align:left;color:#2b2f38;width:20%;">Aspect</th>
                    <th style="padding:14px 16px;text-align:left;color:#2b2f38;width:40%;">Thesis</th>
                    <th style="padding:14px 16px;text-align:left;color:#2b2f38;width:40%;">Dissertation</th>
                </tr>
                <tr style="border-bottom:1px solid #eceff4;">
                    <td style="padding:14px 16px;color:#12203f;font-weight:700;vertical-align:top;">Regional usage</td>
                    <td style="padding:14px 16px;color:#2b2f38;vertical-align:top;">In the UK, India, and Australia, a
                        thesis is the document required to earn a PhD or doctoral degree, representing the highest level
                        of academic writing a student will produce. In the USA and Canada, the term flips — a thesis
                        refers to the Master's-level document, submitted before students move on to doctoral study.</td>
                    <td style="padding:14px 16px;color:#2b2f38;vertical-align:top;">In the UK, India, and Australia, a
                        dissertation is the document submitted at the undergraduate or Master's level, usually shorter
                        and less research-intensive than a PhD thesis. In the USA and Canada, this term is reserved for
                        the doctoral capstone, making it the most extensive and rigorous piece of academic writing a
                        student will ever produce.</td>
                </tr>
                <tr style="border-bottom:1px solid #eceff4;background:#f9fafc;">
                    <td style="padding:14px 16px;color:#12203f;font-weight:700;vertical-align:top;">Purpose and
                        academic expectation</td>
                    <td style="padding:14px 16px;color:#2b2f38;vertical-align:top;">A thesis is built around presenting
                        an original argument, position, or interpretation using existing knowledge, theories, and
                        secondary research. The core expectation is that the student demonstrates mastery of the subject
                        and the ability to construct a well-reasoned, evidence-backed case rather than necessarily
                        generating brand-new data.</td>
                    <td style="padding:14px 16px;color:#2b2f38;vertical-align:top;">A dissertation is expected to make
                        an original contribution to the field, meaning the student must identify a genuine gap in
                        existing research and fill it through primary research, experiments, or fieldwork. This makes it
                        a much heavier undertaking, since the work must hold up to scrutiny as a new addition to
                        academic knowledge.</td>
                </tr>
                <tr>
                    <td style="padding:14px 16px;color:#12203f;font-weight:700;vertical-align:top;">Length, research
                        depth, and process</td>
                    <td style="padding:14px 16px;color:#2b2f38;vertical-align:top;">Typically 20,000–80,000 words
                        depending on country and academic level, and may or may not require original data since it can
                        be argument-driven and based on secondary sources. Usually completed within a single semester to
                        a year, guided by one supervisor, with a comparatively shorter defense process.</td>
                    <td style="padding:14px 16px;color:#2b2f38;vertical-align:top;">Length ranges widely — from around
                        8,000 words at the undergraduate level to well over 100,000 words for doctoral work — and almost
                        always requires original primary data. Guided by a full committee of advisors, spans two to
                        seven years at doctoral level, and concludes with an extensive viva voce before an examination
                        panel, often followed by an expectation to publish in peer-reviewed journals.</td>
                </tr>
